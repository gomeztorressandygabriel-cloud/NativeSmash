#!/usr/bin/env python3
"""Compile the FSR 1 shaders (runtime/fsr1/*.hlsl, with AMD's headers in third_party/fsr1/) to
runtime/gpu_fsr_shaders.h, so that the game carries them:

- for Direct3D 11, their DXBC (gpu_fsr.c), as C byte arrays: the game compiles nothing;
- for Vulkan, their source preprocessed with FSR_VULKAN (AMD's headers in it, its comments and
  unused branches out), which gpu_vk.c makes SPIR-V the first time FSR draws.

Run it again only when a shader changes (it needs fxc, from the Windows SDK).

  python tools/make_fsr1.py
"""
import glob
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = [("easu", "fsr1_easu"), ("rcas", "fsr1_rcas")]


def find_fxc():
    for pattern in (r"C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe",
                    r"C:\Program Files\Windows Kits\10\bin\*\x64\fxc.exe"):
        found = sorted(glob.glob(pattern))
        if found:
            return found[-1]
    sys.exit("fxc.exe not found: install the Windows SDK (it comes with Visual Studio's C++ tools).")


def as_array(out, symbol, data):
    out.append(f"static const unsigned char {symbol}[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append("")


def main():
    fxc = find_fxc()
    inc = os.path.join(ROOT, "third_party", "fsr1")
    out = [
        "/* Generated by tools/make_fsr1.py from runtime/fsr1/*.hlsl: AMD's FidelityFX Super Resolution 1 passes",
        " * (third_party/fsr1/, MIT, (c) 2021 Advanced Micro Devices, Inc.) - *_ps: Direct3D 11's DXBC; *_vk_hlsl:",
        " * the source for Vulkan (FSR_VULKAN, preprocessed, NUL-terminated), included with FSR_VULKAN_SOURCE.",
        " * Do not edit. */",
        "#pragma once",
        "",
    ]
    vk = ["#ifdef FSR_VULKAN_SOURCE", ""]
    out.append("#ifndef FSR_VULKAN_SOURCE")
    out.append("")
    with tempfile.TemporaryDirectory() as tmp:
        for name, symbol in SHADERS:
            src = os.path.join(ROOT, "runtime", "fsr1", name + ".hlsl")
            obj = os.path.join(tmp, name + ".dxbc")
            r = subprocess.run([fxc, "/nologo", "/T", "ps_5_0", "/E", "main", "/O3", "/I", inc, "/Fo", obj, src],
                               capture_output=True, text=True)
            if not os.path.exists(obj):
                sys.exit(f"{name}.hlsl failed:\n{r.stdout}{r.stderr}")
            data = open(obj, "rb").read()
            as_array(out, symbol + "_ps", data)
            pre = os.path.join(tmp, name + ".vk.hlsl")
            r = subprocess.run([fxc, "/nologo", "/D", "FSR_VULKAN=1", "/I", inc, "/P", pre, src], capture_output=True, text=True)
            if not os.path.exists(pre):
                sys.exit(f"{name}.hlsl (Vulkan) could not be preprocessed:\n{r.stdout}{r.stderr}")
            lines = [ln.rstrip() for ln in open(pre, encoding="utf-8", errors="replace").read().splitlines()]
            text = "\n".join(ln for ln in lines if ln and not ln.startswith("#line")) + "\n"
            as_array(vk, symbol + "_vk_hlsl", text.encode() + b"\0")
            print(f"{name}: {len(data)} bytes of DXBC, {len(text)} of Vulkan source")
    out += ["#endif", ""] + vk + ["#endif", ""]
    path = os.path.join(ROOT, "runtime", "gpu_fsr_shaders.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
