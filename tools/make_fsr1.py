#!/usr/bin/env python3
"""Compile the FSR 1 shaders (runtime/fsr1/*.hlsl, with AMD's headers in third_party/fsr1/) to
runtime/gpu_fsr_shaders.h: their DXBC as C byte arrays, so that the game carries them and never
compiles them. Run it again only when a shader changes (it needs fxc, from the Windows SDK).

  python tools/make_fsr1.py
"""
import glob
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = [("easu", "fsr1_easu_ps"), ("rcas", "fsr1_rcas_ps")]


def find_fxc():
    for pattern in (r"C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe",
                    r"C:\Program Files\Windows Kits\10\bin\*\x64\fxc.exe"):
        found = sorted(glob.glob(pattern))
        if found:
            return found[-1]
    sys.exit("fxc.exe not found: install the Windows SDK (it comes with Visual Studio's C++ tools).")


def main():
    fxc = find_fxc()
    out = [
        "/* Generated by tools/make_fsr1.py from runtime/fsr1/*.hlsl: the DXBC of AMD's FidelityFX Super",
        " * Resolution 1 passes (third_party/fsr1/, MIT, (c) 2021 Advanced Micro Devices, Inc.). Do not edit. */",
        "#pragma once",
        "",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for name, symbol in SHADERS:
            obj = os.path.join(tmp, name + ".dxbc")
            cmd = [fxc, "/nologo", "/T", "ps_5_0", "/E", "main", "/O3", "/I", os.path.join(ROOT, "third_party", "fsr1"),
                   "/Fo", obj, os.path.join(ROOT, "runtime", "fsr1", name + ".hlsl")]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if not os.path.exists(obj):
                sys.exit(f"{name}.hlsl failed:\n{r.stdout}{r.stderr}")
            data = open(obj, "rb").read()
            out.append(f"static const unsigned char {symbol}[{len(data)}] = {{")
            for i in range(0, len(data), 16):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
            out.append("};")
            out.append("")
            print(f"{name}: {len(data)} bytes")
    path = os.path.join(ROOT, "runtime", "gpu_fsr_shaders.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
